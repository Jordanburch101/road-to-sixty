"""Writes one client's minimap terrain tiles as a file of the addon's, from
that build's file list on wago.tools:

  RoadToSixty/MinimapTiles<Name>.lua   ns.MinimapTiles[<Key>] = { ["COL_ROW"] = fileID, ... }
                                       for each folder:Key given

for world/minimaps/<folder>/mapCOL_ROW.blp, the same layout as MinimapTiles.lua
(Forever's, whose own generator is not in the repo). Map.lua's
ns.MinimapDirs names the key for each continent ID. The file loads only
where ns.<Flag> is true, and replaces those keys there.

Forever has terrain the classic clients lack (370 Eastern Kingdoms tiles
the Anniversary realms do not have, drawn green or as the wrong place's
ground, Jordan 2026-10-26), so each classic client gets its own lists:

  python scripts/minimap-tiles.py 2.5.6.70006 Anniversary Anniversary azeroth:Azeroth kalimdor:Kalimdor expansion01:Expansion01
  python scripts/minimap-tiles.py 1.15.9.70003 Era Era azeroth:Azeroth kalimdor:Kalimdor
"""
import json
import re
import sys
import time
import urllib.request
from pathlib import Path

BUILD, NAME, FLAG = sys.argv[1], sys.argv[2], sys.argv[3]
FOLDERS = [arg.split(":") for arg in sys.argv[4:]]
OUT = Path(__file__).resolve().parent.parent / "RoadToSixty" / f"MinimapTiles{NAME}.lua"


def search(prefix):
    url = f"https://wago.tools/api/files?search={prefix}&version={BUILD}"
    req = urllib.request.Request(url, headers={"User-Agent": "RoadToSixty minimap tiles"})
    for attempt in range(5):
        try:
            with urllib.request.urlopen(req, timeout=60) as resp:
                return json.loads(resp.read())
        except OSError:
            if attempt == 4:
                raise
            time.sleep(5 * (attempt + 1))


def tiles_of(folder):
    tiles = {}
    # (one search per first digit of the column: a single search may be cut short)
    for digit in "0123456789":
        found = search(f"world/minimaps/{folder}/map{digit}")
        for file_id, path in (found.items() if isinstance(found, dict) else []):
            m = re.fullmatch(rf"world/minimaps/{folder}/map(\d+)_(\d+)\.blp", path)
            if m:
                tiles[f"{int(m.group(1))}_{int(m.group(2))}"] = int(file_id)
    return tiles


def order(k):
    col, row = k.split("_")
    return int(col), int(row)


def main():
    lines = [
        "local _, ns = ...",
        "",
        f"-- Minimap terrain tile file IDs for this client (build {BUILD}, from wago.tools'",
        "-- file list), replacing Forever's lists in MinimapTiles.lua, which hold tiles",
        "-- this client lacks. Generated by scripts/minimap-tiles.py, do not edit by hand.",
        "-- Key is \"COL_ROW\" from the tile name mapCOL_ROW, as in MinimapTiles.lua.",
        "",
        f"if not ns.{FLAG} then return end",
    ]
    for folder, key in FOLDERS:
        tiles = tiles_of(folder.lower())
        lines += ["", f"ns.MinimapTiles[\"{key}\"] = {{"]
        lines += [f"    [\"{k}\"] = {tiles[k]}," for k in sorted(tiles, key=order)]
        lines.append("}")
        print(f"{folder}: {len(tiles)} tiles")
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print(f"-> {OUT}")


if __name__ == "__main__":
    main()
