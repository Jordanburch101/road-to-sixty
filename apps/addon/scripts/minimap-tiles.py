"""Writes the minimap terrain tiles of one minimap folder as a file of the
addon's, from the client's file list on wago.tools:

  RoadToSixty/MinimapTiles<Name>.lua   ns.MinimapTiles[<Name>] = { ["COL_ROW"] = fileID, ... }

for world/minimaps/<folder>/mapCOL_ROW.blp, the same layout as MinimapTiles.lua
(whose own generator is not in the repo). Map.lua's ns.MinimapDirs names the
folder for each continent ID.

Expansion01 is world 530 (the Anniversary realms' Outland, and the Blood Elf
and Draenei lands), so its file loads only there (#75):

  python scripts/minimap-tiles.py 2.5.6.70006 expansion01 Expansion01 Anniversary
"""
import json
import re
import sys
import urllib.request
from pathlib import Path

BUILD, FOLDER, NAME = sys.argv[1], sys.argv[2].lower(), sys.argv[3]
ONLY = sys.argv[4] if len(sys.argv) > 4 else None    # an ns flag the file needs, such as Anniversary
OUT = Path(__file__).resolve().parent.parent / "RoadToSixty" / f"MinimapTiles{NAME}.lua"


def search(prefix):
    url = f"https://wago.tools/api/files?search={prefix}&version={BUILD}"
    req = urllib.request.Request(url, headers={"User-Agent": "RoadToSixty minimap tiles"})
    with urllib.request.urlopen(req) as resp:
        return json.loads(resp.read())


def main():
    tiles = {}
    # (one search per first digit of the column: a single search may be cut short)
    for digit in "0123456789":
        found = search(f"world/minimaps/{FOLDER}/map{digit}")
        for file_id, path in (found.items() if isinstance(found, dict) else []):
            m = re.fullmatch(rf"world/minimaps/{FOLDER}/map(\d+)_(\d+)\.blp", path)
            if m:
                tiles[f"{int(m.group(1))}_{int(m.group(2))}"] = int(file_id)
    def key(k):
        col, row = k.split("_")
        return int(col), int(row)
    lines = [
        "local _, ns = ...",
        "",
        f"-- Minimap terrain tile file IDs of world/minimaps/{FOLDER}/ (build {BUILD}, from",
        "-- wago.tools' file list). Generated by scripts/minimap-tiles.py, do not edit by hand.",
        "-- Key is \"COL_ROW\" from the tile name mapCOL_ROW, as in MinimapTiles.lua.",
        "",
    ]
    if ONLY:
        lines += [f"if not ns.{ONLY} then return end", ""]
    lines.append(f"ns.MinimapTiles.{NAME} = {{")
    lines += [f"    [\"{k}\"] = {tiles[k]}," for k in sorted(tiles, key=key)]
    lines.append("}")
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print(f"{len(tiles)} tiles -> {OUT}")


if __name__ == "__main__":
    main()
