"""Writes one client's minimap terrain tiles as a file of the addon's, from
that build's world files on wago.tools:

  RoadToSixty/MinimapTiles<Name>.lua   ns.MinimapTiles[<Key>] = { ["COL_ROW"] = fileID, ... }
                                       for each folder:Key given

for the world world/maps/<folder>/<folder>.wdt: its MAID chunk holds, for
each of its 64 x 64 tiles, eight file IDs, the last that tile's minimap
texture (zero where there is no tile). The file list by name is no guide:
it names tiles the world no longer uses (167 of its 854 Eastern Kingdoms
names on Anniversary), drawn as black or olive squares (Jordan,
2026-10-26). Same layout as MinimapTiles.lua (Forever's, whose own
generator is not in the repo); keys are mapCOL_ROW's. Map.lua's
ns.MinimapDirs names the key for each continent ID. The file loads only
where ns.<Flag> is true, and replaces those keys there.

Forever has terrain the classic clients lack (370 Eastern Kingdoms tiles
the Anniversary realms do not have, drawn green or as the wrong place's
ground, Jordan 2026-10-26), so each classic client gets its own lists:

  python scripts/minimap-tiles.py 2.5.6.70006 Anniversary Anniversary azeroth:Azeroth kalimdor:Kalimdor expansion01:Expansion01
  python scripts/minimap-tiles.py 1.15.9.70003 Era Era azeroth:Azeroth kalimdor:Kalimdor
"""
import json
import struct
import sys
import time
import urllib.request
from pathlib import Path

BUILD, NAME, FLAG = sys.argv[1], sys.argv[2], sys.argv[3]
FOLDERS = [arg.split(":") for arg in sys.argv[4:]]
OUT = Path(__file__).resolve().parent.parent / "RoadToSixty" / f"MinimapTiles{NAME}.lua"


def search(prefix):
    url = f"https://wago.tools/api/files?search={prefix}&version={BUILD}"
    req = urllib.request.Request(url, headers={"User-Agent": "RoadToSixty minimap tiles"})
    for attempt in range(5):
        try:
            with urllib.request.urlopen(req, timeout=60) as resp:
                return json.loads(resp.read())
        except OSError:
            if attempt == 4:
                raise
            time.sleep(5 * (attempt + 1))


def fetch(url):
    req = urllib.request.Request(url, headers={"User-Agent": "RoadToSixty minimap tiles"})
    for attempt in range(5):
        try:
            with urllib.request.urlopen(req, timeout=60) as resp:
                return resp.read()
        except OSError:
            if attempt == 4:
                raise
            time.sleep(5 * (attempt + 1))


def tiles_of(folder):
    """The world's minimap tiles from its WDT: "COL_ROW" -> file ID."""
    found = search(f"world/maps/{folder}/{folder}.wdt")
    wdt_id = next(iter(found)) if isinstance(found, dict) and found else None
    if not wdt_id:
        raise SystemExit(f"no WDT for {folder} in {BUILD}")
    data = fetch(f"https://wago.tools/api/casc/{wdt_id}?version={BUILD}")
    i, maid = 0, None
    while i + 8 <= len(data):
        tag, size = data[i:i + 4][::-1], struct.unpack_from("<I", data, i + 4)[0]
        if tag == b"MAID":
            maid = data[i + 8:i + 8 + size]
        i += 8 + size
    if maid is None:
        raise SystemExit(f"{folder}'s WDT has no MAID chunk")
    tiles = {}
    for index in range(64 * 64):
        minimap = struct.unpack_from("<8I", maid, index * 32)[7]
        if minimap:
            row, col = divmod(index, 64)
            tiles[f"{col}_{row}"] = minimap
    return tiles


def order(k):
    col, row = k.split("_")
    return int(col), int(row)


def main():
    lines = [
        "local _, ns = ...",
        "",
        f"-- Minimap terrain tile file IDs for this client (build {BUILD}, from its worlds'",
        "-- WDT files via wago.tools), replacing Forever's lists in MinimapTiles.lua, which hold tiles",
        "-- this client lacks. Generated by scripts/minimap-tiles.py, do not edit by hand.",
        "-- Key is \"COL_ROW\" from the tile name mapCOL_ROW, as in MinimapTiles.lua.",
        "",
        f"if not ns.{FLAG} then return end",
    ]
    for folder, key in FOLDERS:
        tiles = tiles_of(folder.lower())
        lines += ["", f"ns.MinimapTiles[\"{key}\"] = {{"]
        lines += [f"    [\"{k}\"] = {tiles[k]}," for k in sorted(tiles, key=order)]
        lines.append("}")
        print(f"{folder}: {len(tiles)} tiles")
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print(f"-> {OUT}")


if __name__ == "__main__":
    main()
