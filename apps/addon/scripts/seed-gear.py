"""Writes RoadToSixty/SeedGear.lua: the gear /rts seed stress dresses its
warrior in, from the client's own item tables on wago.tools, so the seeded
journey has a believable amount of real gear in every slot (issue #64).

    python scripts/seed-gear.py [build]      (from apps/addon; default below)

For each slot it keeps what a warrior can wear (mail, plate from level 40,
one-handed axes, maces and swords, shields, bows, guns and crossbows, and
any neck, ring, trinket and cloak), up to two items per quality and
required level (more at 58 to 60, for the pre-raid and raid gear), and the
enchants an enchanter would put on them.
"""

import csv
import io
import re
import sys
import urllib.request

BUILD = sys.argv[1] if len(sys.argv) > 1 else "1.60.1.70532"
OUT = "RoadToSixty/SeedGear.lua"

# Inventory slot -> the item InventoryType values that go in it.
SLOTS = {
    1: [1], 2: [2], 3: [3], 5: [5, 20], 6: [6], 7: [7], 8: [8], 9: [9], 10: [10],
    11: [11], 13: [12], 15: [16], 16: [13, 21], 17: [14], 18: [15, 26],
}
ARMOUR = {1, 3, 5, 20, 6, 7, 8, 9, 10}
MAIL, PLATE, SHIELD = 3, 4, 6
ONE_HANDERS = {0, 4, 7}             # axe, mace, sword
RANGED = {2, 3, 18}                 # bow, gun, crossbow
WARRIOR = 1                         # AllowableClass bit
NOT_REAL = re.compile(r"(test|monster|deprecated|\bqa\b|\[ph\]|\bph\b|unused|\bold\b|^zz|debug|\bnpc\b|\bdev\b|placeholder)", re.I)

# Enchants by slot (SpellItemEnchantment IDs, checked by name in this build).
ENCHANTS = {
    16: [1900, 803, 1894],          # Crusader, Fiery Weapon, Icy Chill
    5: [1891, 928, 866],            # All Stats +4, +3, +2
    9: [357, 107, 109],             # +9, +5, +7 Strength
    10: [109, 106, 107],            # +7, +4, +5 Strength
    8: [911, 93, 91],               # Minor Speed Increase, +7 Agility, +5 Agility
    15: [76, 87],                   # +3 Agility, +12 Armor
    17: [105, 73],                  # +7 Stamina, +3 Stamina
}


def table(name):
    url = f"https://wago.tools/db2/{name}/csv?build={BUILD}"
    req = urllib.request.Request(url, headers={"User-Agent": "RoadToSixty seed gear generator"})
    with urllib.request.urlopen(req) as response:
        return list(csv.DictReader(io.StringIO(response.read().decode("utf-8"))))


def wearable(item, sparse):
    inv, cls, sub = int(item["InventoryType"]), int(item["ClassID"]), int(item["SubclassID"])
    req = int(sparse["RequiredLevel"])
    if inv in ARMOUR:
        return cls == 4 and (sub == MAIL or sub == PLATE and req >= 40)
    if inv == 14:
        return cls == 4 and sub == SHIELD
    if inv in (13, 21):
        return cls == 2 and sub in ONE_HANDERS
    if inv in (15, 26):
        return cls == 2 and sub in RANGED
    return inv in (2, 11, 12, 16)


def main():
    items = {row["ID"]: row for row in table("Item")}
    names = {}
    pools = {slot: {} for slot in SLOTS}
    for sparse in table("ItemSparse"):
        item = items.get(sparse["ID"])
        if not item:
            continue
        inv, quality = int(sparse["InventoryType"]), int(sparse["OverallQualityID"])
        req, ilvl = int(sparse["RequiredLevel"]), int(sparse["ItemLevel"])
        allowed = int(sparse["AllowableClass"])
        name = sparse["Display_lang"]
        if not (1 <= quality <= 4) or not (1 <= req <= 60) or ilvl > 90 or NOT_REAL.search(name):
            continue
        if allowed not in (-1, 0) and not allowed & WARRIOR:
            continue
        if not wearable(item, sparse):
            continue
        for slot, types in SLOTS.items():
            if inv in types:
                # All raid gear needs level 60, so 60 keeps more to raid through.
                bucket = pools[slot].setdefault((quality, req), [])
                if len(bucket) < (12 if req == 60 and quality == 4 else 6 if req >= 58 else 2):
                    bucket.append((int(sparse["ID"]), req, quality, ilvl))
                    names[int(sparse["ID"])] = name

    lines = [
        "local _, ns = ...",
        "",
        "-- Generated by scripts/seed-gear.py from build " + BUILD + ": do not edit by hand.",
        "-- The gear /rts seed stress dresses its warrior in (Seed.lua):",
        "--   slots[slot]     { { itemID, requiredLevel, quality, itemLevel }, ... } by",
        "--                   required level; rings (11) and trinkets (13) serve both slots",
        "--   enchants[slot]  enchant IDs an enchanter puts on that slot",
        "",
        "ns.SeedGear = { build = \"" + BUILD + "\", slots = {}, enchants = {} }",
        "local slots, enchants = ns.SeedGear.slots, ns.SeedGear.enchants",
    ]
    total = 0
    for slot in sorted(pools):
        entries = sorted((e for bucket in pools[slot].values() for e in bucket), key=lambda e: (e[1], e[3], e[0]))
        total += len(entries)
        body = ", ".join("{ %d, %d, %d, %d }" % e for e in entries)
        lines.append(f"slots[{slot}] = {{ {body} }}")
    for slot in sorted(ENCHANTS):
        lines.append(f"enchants[{slot}] = {{ {', '.join(str(e) for e in ENCHANTS[slot])} }}")
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines) + "\n")
    print(f"{OUT}: {total} items in {len(pools)} slots from build {BUILD}")


if __name__ == "__main__":
    main()
